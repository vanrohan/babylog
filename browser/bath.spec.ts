import {expectEndTime} from './entry-time-helpers.ts';
import {typeEntryTime} from './entry-time-helpers.ts';
import {test,expect} from './test.ts';

test('bath entry supports editing, dashboard filtering, and activity rename',async({page,request},info)=>{
 for(const entry of await (await request.get('/api/entries')).json())await request.delete('/api/entries/'+entry.id,{data:{version:entry.version}});
 await page.goto('/');
 await page.getByRole('button',{name:'Add an entry',exact:true}).click();
 await page.getByRole('textbox',{name:'Diary date',exact:true}).fill('2026-11-03');
 await page.getByRole('button',{name:'Bath',exact:true}).click();
 await expect(page.getByLabel('Still in progress')).toHaveCount(0);
 await typeEntryTime(page,'start','2026-11-03T15:00');
 await typeEntryTime(page,'end','2026-11-03T15:20');
 await page.getByLabel('Notes').fill('Evening bath.');
 await page.getByRole('button',{name:'Save entry',exact:true}).click();
 await expect(page.locator('.timeline-entry')).toContainText('Bath');
 await page.getByLabel('Filter activities').selectOption('bath');
 await page.getByRole('button',{name:'Edit Bath at 15:00',exact:true}).click();
 await expect(page.getByRole('button',{name:'Bath',exact:true})).toHaveAttribute('aria-pressed','true');
 await expectEndTime(page,'2026-11-03T15:20');
 await page.evaluate(()=>window.scrollTo(0,0));
 await page.screenshot({path:info.outputPath('bath-form.png'),fullPage:true});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
 await page.getByLabel('Notes').fill('Updated bath note.');
 await page.getByRole('button',{name:'Save changes',exact:true}).click();await expect(page.locator('#entry-toggle')).toHaveAttribute('aria-expanded','false');
 await page.getByRole('button',{name:'Dashboard',exact:true}).click();
 await page.getByLabel('Dashboard date').fill('2026-11-03');
 await page.getByLabel('Dashboard activity').selectOption('bath');
 await expect(page.locator('.pattern-track.bath .pattern-mark')).toHaveCount(1);
 await expect(page.locator('.pattern-track.other')).toHaveCount(0);
 await page.getByRole('button',{name:/^2026-11-03: 1 entries/}).click();
 await page.getByRole('button',{name:/^Bath 15:00/}).click();
 await expect(page.getByRole('article',{name:'Entry details'})).toContainText('Duration: 20m');
 await expect(page.getByRole('article',{name:'Entry details'})).toContainText('Updated bath note.');
 await page.getByRole('button',{name:'Edit in time log',exact:true}).click();
 await expectEndTime(page,'2026-11-03T15:20');
 await typeEntryTime(page,'end','');
 await expectEndTime(page,'');
 await page.getByRole('button',{name:'Save changes',exact:true}).click();await expect(page.locator('#entry-toggle')).toHaveAttribute('aria-expanded','false');
 await page.getByRole('button',{name:'Dashboard',exact:true}).click();
 await page.getByLabel('Dashboard date').fill('2026-11-03');
 await page.getByLabel('Dashboard activity').selectOption('bath');
 await page.getByRole('button',{name:/^2026-11-03: 1 entries/}).click();
 await page.getByRole('button',{name:/^Bath 15:00/}).click();
 await expect(page.getByRole('article',{name:'Entry details'})).toContainText('Duration: Point event');
 await expect(page.getByRole('article',{name:'Entry details'})).toContainText('End: Not recorded');
 await expect(page.getByLabel('Active timers')).toHaveCount(0);
 await page.getByRole('button',{name:'Edit in time log',exact:true}).click();
 await page.getByRole('button',{name:'Other',exact:true}).click();
 await page.getByLabel('Activity name').fill('Walk');
 await page.getByRole('button',{name:'Save changes',exact:true}).click();await expect(page.locator('#entry-toggle')).toHaveAttribute('aria-expanded','false');
 await page.getByLabel('Filter activities').selectOption('all');
 await expect(page.locator('.timeline-entry')).toContainText('Walk');
 await page.getByRole('button',{name:'Dashboard',exact:true}).click();
 await page.getByLabel('Dashboard date').fill('2026-11-03');
 await page.getByLabel('Dashboard activity').selectOption('bath');
 await expect(page.locator('.pattern-track.bath .pattern-mark')).toHaveCount(0);
});
