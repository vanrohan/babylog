import { test } from 'node:test';
import assert from 'node:assert/strict';
import {testStore} from './postgres-fixture.ts';
import { proposalFeedback } from '../src/feedback.ts';
test('custom task rename preserves identity and history; removal never reuses its key', async (t) => {
    const store = (await testStore());
    t.after(async () => (await store.close()));
    const task = (await store.createCareTask({ label: 'Go for a stroll' }));
    const check = (await store.setCare('2026-11-03', task.key, true, 0, task.version));
    assert.deepEqual(check, { done: true, version: 1 });
    assert.equal((await store.getCare('2026-11-04'))[task.key].done, false);
    const renamed = (await store.updateCareTask(task.key, { label: 'Stroll outside' }, task.version));
    assert.equal(renamed.key, task.key);
    assert.equal(renamed.version, 2);
    assert.deepEqual((await store.getCare('2026-11-03'))[task.key], check);
    await assert.rejects(async () => (await store.updateCareTask(task.key, { label: 'Stale name' }, task.version)), /changed/);
    await assert.rejects(async () => (await store.setCare('2026-11-03', task.key, false, check.version, task.version)), /changed/);
    await assert.rejects(async () => (await store.removeCareTask(task.key, task.version)), /changed/);
    const removed = (await store.removeCareTask(task.key, renamed.version));
    assert.equal(removed.active, false);
    await assert.rejects(async () => (await store.setCare('2026-11-03', task.key, false, check.version)), /removed/);
    await assert.rejects(async () => (await store.propose([{ type: 'set_care', day: '2026-11-03', key: task.key, done: false, version: check.version }], 'Old task.')), /removed/);
    const replacement = (await store.createCareTask({ label: 'Stroll outside' }));
    assert.notEqual(replacement.key, task.key);
    assert.equal((await store.getCare('2026-11-03'))[replacement.key].done, false);
    const exported = (await store.exportData());
    assert.equal(exported.care.find(row => row.key === task.key)?.done, 1);
    assert.equal(exported.careTasks.find(row => row.key === task.key)?.active, false);
});
test('task proposals snapshot labels and reject renamed or removed tasks in one transaction', async (t) => {
    const store = (await testStore());
    t.after(async () => (await store.close()));
    const task = (await store.createCareTask({ label: 'Air out apartment' }));
    const input = { type: 'set_care', day: '2026-11-03', key: task.key, done: true, version: 0 };
    const proposed = (await store.propose([input], 'Air out apartment.'));
    const op = proposed.operations[0];
    assert.equal(op.type, 'set_care');
    if (op.type !== 'set_care')
        throw new Error('Expected daily task.');
    assert.equal(op.taskLabel, task.label);
    assert.equal(op.taskVersion, 1);
    assert.match(proposalFeedback(proposed).message, /Air out apartment marked done/);
    assert.equal((await store.getCare('2026-11-03'))[task.key].done, false);
    const renamed = (await store.updateCareTask(task.key, { label: 'Open the windows' }, 1));
    await assert.rejects(async () => (await store.confirm(proposed.id)), /changed/);
    assert.equal((await store.getCare('2026-11-03'))[task.key].done, false);
    const batch = (await store.propose([{ type: 'create_entry', entry: { activity: 'note', startAt: '2026-11-03T10:00:00Z' } }, input], 'Add a note and check.'));
    (await store.removeCareTask(task.key, renamed.version));
    await assert.rejects(async () => (await store.confirm(batch.id)), /removed/);
    assert.equal((await store.listEntries()).length, 0);
    assert.equal((await store.getProposal(batch.id)).status, 'pending');
    const valid = (await store.createCareTask({ label: 'Go for a stroll' }));
    const accepted = (await store.propose([{ ...input, key: valid.key }], 'Stroll complete.'));
    (await store.confirm(accepted.id));
    assert.equal((await store.getCare('2026-11-03'))[valid.key].done, true);
});
test('daily tasks reject unknown keys, blank names, duplicate names, and invalid versions', async (t) => {
    const store = (await testStore());
    t.after(async () => (await store.close()));
    for (const label of ['', '   ', 'x'.repeat(81), 'Two\nlines'])
        await assert.rejects(async () => (await store.createCareTask({ label })));
    await assert.rejects(async () => (await store.createCareTask({ label: ' tummy TIME ' })), /already uses/);
    await assert.rejects(async () => (await store.setCare('2026-11-03', 'unknown', true, 0)), /not found/);
    await assert.rejects(async () => (await store.propose([{ type: 'set_care', day: '2026-11-03', key: 'unknown', done: true, version: 0 }], 'Unknown.')), /not found/);
    await assert.rejects(async () => (await store.setCare('2026-11-03', '__proto__', true, 0)));
    const task = (await store.createCareTask({ label: 'Go for a stroll' }));
    await assert.rejects(async () => (await store.updateCareTask(task.key, { label: 'Tummy time' }, task.version)), /already uses/);
    await assert.rejects(async () => (await store.updateCareTask(task.key, { label: 'Stroll' }, 0)));
    assert.equal((await store.getCareTask(task.key)).label, task.label);
});
